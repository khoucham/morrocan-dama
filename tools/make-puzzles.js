/* Finds tactic puzzles with the real rules engine and writes src/puzzles.js.
   A puzzle is a position (Ivory to move, no capture available) where exactly ONE first move wins material
   by force: the opponent is forced to capture, and then Ivory captures more than it lost, whatever the
   opponent was allowed to choose. Run: node tools/make-puzzles.js */
const fs = require('fs'), path = require('path');
const E = require('../src/engine.js');

let seed = 20261103;
const rnd = () => { seed |= 0; seed = seed + 0x6D2B79F5 | 0; let t = Math.imul(seed ^ seed >>> 15, 1 | seed); t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t; return ((t ^ t >>> 14) >>> 0) / 4294967296; };
const dark = []; for (let i = 0; i < 64; i++) if ((((i >> 3) + (i & 7)) & 1) === 1) dark.push(i);

/* How much does Ivory (side 1) net after moving m? Worst case over every reply the opponent may choose.
   Returns null unless the opponent is forced to capture and Ivory always has a capture afterwards. */
function forcedGain(b, m) {
  const b2 = E.applyMove(b, m);
  const replies = E.genMoves(b2, -1);
  if (!replies.length || !replies[0].caps.length) return null;
  let worst = Infinity;
  for (const r of replies) {
    const b3 = E.applyMove(b2, r);
    const mine = E.genMoves(b3, 1);
    if (!mine.length || !mine[0].caps.length) return null;
    const lost = r.caps.length, won = mine[0].caps.length;
    worst = Math.min(worst, won - lost);
  }
  return worst;
}

function randomPosition() {
  const b = new Int8Array(64);
  const place = (n, v, rmin, rmax) => { let k = 0, g = 0; while (k < n && g++ < 200) { const i = dark[Math.floor(rnd() * dark.length)], r = i >> 3; if (b[i] || r < rmin || r > rmax) continue; b[i] = v; k++; } };
  const mine = 3 + Math.floor(rnd() * 4), theirs = 3 + Math.floor(rnd() * 4);
  place(mine, 1, 2, 7); place(theirs, -1, 0, 6);
  if (rnd() < 0.12) place(1, 2, 3, 7);             // sometimes an Ivory king
  if (rnd() < 0.12) place(1, -2, 0, 5);            // sometimes a Ruby king
  return b;
}

const found = [];
const seen = new Set();
for (let t = 0; t < 6000000 && found.length < 400; t++) {
  const b = randomPosition();
  if (E.genMoves(b, 1).some(m => m.caps.length) || E.genMoves(b, -1).some(m => m.caps.length)) continue;
  const moves = E.genMoves(b, 1);
  const wins = moves.filter(m => { const g = forcedGain(b, m); return g !== null && g >= 1; });
  if (wins.length !== 1) continue;                 // exactly one winning first move
  const m = wins[0], gain = forcedGain(b, m);
  const key = Array.from(b).join();
  if (seen.has(key)) continue; seen.add(key);
  const pieces = Array.from(b).filter(x => x).length;
  const kings = Array.from(b).filter(x => Math.abs(x) === 2).length;
  found.push({ b, m, gain, pieces, kings, replies: E.genMoves(E.applyMove(b, m), -1).length, quiet: moves.length });
}
console.log('candidates:', found.length);

/* order from easy to hard: fewer pieces and fewer legal moves are easier to read; bigger gains and kings are harder */
const score = p => p.pieces * 2 + p.quiet * 0.6 + p.gain * 5 + p.kings * 4 + p.replies;
found.sort((a, b) => score(a) - score(b));
const pick = [];
const step = Math.max(1, Math.floor(found.length / 16));
for (let i = 0; i < found.length && pick.length < 16; i += step) pick.push(found[i]);

const sym = v => v === 1 ? 'o' : v === 2 ? 'O' : v === -1 ? 'x' : v === -2 ? 'X' : '.';
const list = pick.map((p, i) => ({
  n: i + 1,
  board: Array.from(p.b).map(sym).join(''),
  from: p.m.from, path: p.m.path, gain: p.gain,
  text: E.moveText(p.m)
}));
const out = '/* Generated by tools/make-puzzles.js with the rules engine. Do not edit by hand.\n   board: 64 characters, row 0 first. o / O = Ivory man / king, x / X = Ruby man / king. Ivory moves first. */\n' +
  'const DAMA_PUZZLES = ' + JSON.stringify(list, null, 1).replace(/\n\s+/g, ' ').replace(/\[ /g, '[').replace(/ \]/g, ']').replace(/\}, \{/g, '},\n  {').replace(/^\[\{/, '[\n  {').replace(/\}\]$/, '}\n]') + ';\nif (typeof module !== \'undefined\') module.exports = DAMA_PUZZLES;\n';
fs.writeFileSync(path.join(__dirname, '..', 'src', 'puzzles.js'), out);
console.log('wrote', list.length, 'puzzles; gains:', list.map(p => p.gain).join(','), '| pieces:', pick.map(p => p.pieces).join(','));
